def apply_experiment_preset(cfg: SRMAPPOConfig, line: str | None) -> SRMAPPOConfig:
    normalized = normalize_experiment_line(line)
    updated = deepcopy(cfg)
    updated.training.experiment_line = normalized

    if normalized == EXPERIMENT_MANUAL:
        return updated

    if normalized == EXPERIMENT_PHASE0_COMMITTED_PHASEA_ON_CLEAN:
        # Start from the base (manual) configuration and apply only the minimal overrides
        # needed for a clean diagnostic line. Do NOT inherit EXPERIMENT_FULL recipe.
        updated.training.run_name = "sr_mappo_phase0_committed_phasea_on_clean"
        updated.env.phase = "phase0_phasea_fixed_snapshot"
        updated.env.learn_embb_baseline = True
        updated.env.phase0_owner_change_budget_mode = "committed_only"
        updated.env.allow_phase_a_embb_power_adjustment = True

        # Remove contamination from shield/rewrite/fallback paths.
        updated.shield.enable_feasibility_shield = False
        updated.shield.apply_joint_reliability_rewrite = False
        updated.shield.enable_greedy_fallback = False

        # Keep diagnostic line clean: explicitly keep distillation/BC/teacher guidance OFF.
        updated.training.teacher_guidance_decay_start_frac = 0.0
        updated.training.teacher_guidance_decay_end_frac = 0.0
        updated.training.teacher_guidance_final_scale = 0.0

        updated.training.bc_episodes = 0
        updated.training.bc_epochs = 0

        updated.training.use_teacher_distillation = False
        updated.training.teacher_distill_coef_start = 0.0
        updated.training.teacher_distill_coef_end = 0.0
        updated.training.teacher_distill_end_frac = 0.0
        updated.training.teacher_admission_loss_weight = 0.0
        updated.training.teacher_mode_loss_weight = 0.0

        updated.training.use_greedy_reference_bc = False
        updated.training.greedy_bc_coef_start = 0.0
        updated.training.greedy_bc_coef_end = 0.0
        updated.training.greedy_bc_end_frac = 0.0
        updated.training.greedy_bc_warmup_iters = 0
        updated.training.greedy_bc_mode_weight = 0.0
        updated.training.greedy_bc_packet_weight = 0.0
        updated.training.greedy_bc_owner_weight = 0.0

        # Ensure the trainer never enables greedy fallback during warmup.
        updated.training.greedy_fallback_warmup_iterations = 0
        return updated

    if normalized == EXPERIMENT_PHASE0_COMMITTED_PHASEA_ON_CLEAN_NO_POWER_PROJECTION_DEBUG:
        updated = apply_experiment_preset(updated, EXPERIMENT_PHASE0_COMMITTED_PHASEA_ON_CLEAN)
        updated.training.experiment_line = normalized
        updated.training.run_name = "sr_mappo_phase0_committed_phasea_on_clean_no_power_projection_debug"
        updated.env.disable_phase_a_embb_power_projection_for_debug = True
        return updated

    if normalized == EXPERIMENT_PHASE0_COMMITTED_PHASEA_ON_CLEAN_VS_MYOPIC_FORCE_SEPARATION:
        # Base: keep the same clean control line (no shield/rewrite/fallback, no BC/distill/teacher).
        updated = apply_experiment_preset(updated, EXPERIMENT_PHASE0_COMMITTED_PHASEA_ON_CLEAN)
        updated.training.experiment_line = normalized
        updated.training.run_name = "sr_mappo_phase0_committed_phasea_on_clean_vs_myopic_force_separation"

        # Baseline: force report comparison baseline back to admission-suppressing greedy.
        updated.training.greedy_baseline_mode = "myopic_throughput_greedy"
        updated.training.selection_baseline_mode = "myopic_throughput_greedy"

        # Ensure evaluation includes the myopic baseline series.
        modes = list(getattr(updated.training, "eval_compare_modes", []) or [])
        if "myopic_throughput" not in {str(item).strip().lower() for item in modes}:
            modes.append("myopic_throughput")
        updated.training.eval_compare_modes = modes

        # Amplify Phase-A eMBB power control (while keeping projection enabled).
        # This increases the delta->scale leverage and widens the feasible scale band so deltas are not immediately clipped.
        updated.action.embb_power_delta_limit = 1.00
        updated.env.embb_power_scale_min = 0.60
        updated.env.embb_power_scale_max = 1.60

        # Avoid mode collapse by maintaining exploration pressure on mode head.
        updated.training.entropy_coef = 0.02

        # Reward: increase the relative importance of URLLC admission while keeping throughput tradeoff visible.
        updated.reward.terminal_embb_rate_weight = 1.00
        updated.reward.terminal_urllc_admission_weight = 1.00
        updated.reward.power_penalty_scale = 0.05

        # Checkpoint selection: avoid selecting greedy-like throughput-only solutions.
        updated.training.primary_checkpoint_preference = "best_balanced"
        updated.training.balanced_checkpoint_throughput_weight = 0.50
        updated.training.balanced_checkpoint_admission_weight = 0.50
        return updated

    if normalized == EXPERIMENT_PHASE0_COMMITTED_PHASEA_UNCLIPPED_POWER:
        # Goal: force the executed Phase-A eMBB power path to meaningfully deviate from baseline behavior
        # by relaxing the projection/cap/floor binding and weakening the power-anchor constraint.
        updated = apply_experiment_preset(updated, EXPERIMENT_PHASE0_COMMITTED_PHASEA_ON_CLEAN)
        updated.training.experiment_line = normalized
        updated.training.run_name = "sr_mappo_phase0_committed_phasea_unclipped_power"

        # Baseline comparison: always compare against the admission-suppressing myopic throughput greedy.
        updated.training.greedy_baseline_mode = "myopic_throughput_greedy"
        updated.training.selection_baseline_mode = "myopic_throughput_greedy"
        modes = list(getattr(updated.training, "eval_compare_modes", []) or [])
        if "myopic_throughput" not in {str(item).strip().lower() for item in modes}:
            modes.append("myopic_throughput")
        updated.training.eval_compare_modes = modes

        # Phase-A executed power path: loosen everything without affecting other experiments.
        updated.action.embb_power_delta_limit = 1.50
        updated.env.embb_power_scale_min = 0.50
        updated.env.embb_power_scale_max = 1.70
        updated.env.phase_a_embb_power_scale_bound_relax = 1.50
        updated.env.disable_phase_a_embb_power_projection_for_debug = False

        # Anchor: weaken/disable the auxiliary binding so the policy can explore more freely.
        updated.training.use_phase_a_embb_power_anchor = False
        updated.training.phase_a_embb_power_anchor_weight = 0.0

        # Phase-0 owner control: remove implicit "candidate[0]" fallback and ensure the policy
        # cannot silently collapse to the baseline via null-owner snapping.
        # Phase-0 owner exploration: allow null selection, but do NOT fall back to candidates[0].
        updated.env.force_embb_owner_per_rb = False
        updated.env.phase0_owner_fallback_policy = "keep_snapshot"

        # Joint decision: enable Phase-A eMBB power head.
        updated.env.allow_phase_a_embb_power_adjustment = True

        # Faster debug: reduce eval/checkpoint frequency during training.
        updated.training.eval_every = 100
        updated.training.checkpoint_every = 100
        updated.training.light_eval_every = 100

        # Report defaults: emit only the minimal debug plots for this line.
        updated.training.report_fast_debug = True

        # Exploration & selection: reduce mode collapse and avoid selecting greedy-like throughput-only policies.
        updated.training.entropy_coef = 0.02
        updated.training.primary_checkpoint_preference = "best_balanced"
        updated.training.balanced_checkpoint_throughput_weight = 0.45
        updated.training.balanced_checkpoint_admission_weight = 0.55
        return updated

    if normalized == EXPERIMENT_PHASE0_COMMITTED_PHASEA_FLOOR_RELAXED_DEBUG:
        # Floor-relax debug: isolate whether the lower-bound binding is the dominant cause of executed power shrink.
        updated = apply_experiment_preset(updated, EXPERIMENT_PHASE0_COMMITTED_PHASEA_UNCLIPPED_POWER)
        updated.training.experiment_line = normalized
        updated.training.run_name = "sr_mappo_phase0_committed_phasea_floor_relaxed_debug"

        # Strongly relax floor-side binding while keeping cap-side closer to the original window.
        updated.env.phase_a_embb_power_scale_floor_relax = 3.00
        updated.env.phase_a_embb_power_scale_cap_relax = 1.25
        return updated

    if normalized == EXPERIMENT_PHASE0_JOINT_OWNER_POWER_DECOUPLED:
        updated = apply_experiment_preset(updated, EXPERIMENT_PHASE0_COMMITTED_PHASEA_ON_CLEAN)
        updated.training.experiment_line = normalized
        updated.training.run_name = "sr_mappo_phase0_joint_owner_power_decoupled"

        # Baseline fixed to myopic throughput greedy.
        updated.training.greedy_baseline_mode = "myopic_throughput_greedy"
        updated.training.selection_baseline_mode = "myopic_throughput_greedy"
        modes = list(getattr(updated.training, "eval_compare_modes", []) or [])
        if "myopic_throughput" not in {str(item).strip().lower() for item in modes}:
            modes.append("myopic_throughput")
        updated.training.eval_compare_modes = modes

        # Joint freedom: Phase-A power on, no anchor, owner can be null but never falls back to candidate0.
        updated.env.allow_phase_a_embb_power_adjustment = True
        updated.training.use_phase_a_embb_power_anchor = False
        updated.training.phase_a_embb_power_anchor_weight = 0.0
        updated.env.force_embb_owner_per_rb = False
        updated.env.phase0_owner_fallback_policy = "keep_snapshot"

        # Keep the "clean" control (no shield / rewrite / fallback / teacher / distill / BC).
        updated.shield.enable_feasibility_shield = False
        updated.shield.apply_joint_reliability_rewrite = False
        updated.shield.enable_greedy_fallback = False
        updated.training.use_greedy_reference_bc = False
        updated.training.use_teacher_distillation = False
        updated.training.teacher_distill_coef = 0.0
        updated.training.greedy_bc_coef = 0.0
        updated.training.teacher_guidance_scale = 0.0
        updated.training.bc_episodes = 0
        updated.training.bc_epochs = 0
        updated.training.greedy_fallback_warmup_iterations = 0

        # Separation-oriented reward shaping (new optional terms).
        updated.reward.embb_positive_rate_bonus_weight = 0.25
        updated.reward.embb_service_ratio_bonus_weight = 0.25
        updated.reward.power_overuse_penalty_weight = 0.05
        updated.reward.owner_change_utilization_bonus_weight = 0.50

        # Training workflow
        updated.training.eval_every = 100
        updated.training.checkpoint_every = 100
        updated.training.light_eval_every = 100
        updated.training.report_fast_debug = True
        return updated

    if normalized == EXPERIMENT_PHASE0_OWNER_EFFECTIVE_SEPARATION_DEBUG:
        # Owner-first separation: turn off Phase-A power to avoid power masking owner issues,
        # and ensure null/invalid owner decisions cannot silently restore back to snapshot.
        updated = apply_experiment_preset(updated, EXPERIMENT_PHASE0_COMMITTED_PHASEA_ON_CLEAN)
        updated.training.experiment_line = normalized
        updated.training.run_name = "sr_mappo_phase0_owner_effective_separation_debug"

        # Baseline fixed to myopic throughput greedy.
        updated.training.greedy_baseline_mode = "myopic_throughput_greedy"
        updated.training.selection_baseline_mode = "myopic_throughput_greedy"
        modes = list(getattr(updated.training, "eval_compare_modes", []) or [])
        if "myopic_throughput" not in {str(item).strip().lower() for item in modes}:
            modes.append("myopic_throughput")
        updated.training.eval_compare_modes = modes

        # Joint decision freedom (owner only): allow owner to be null; never restore to snapshot on invalid/null.
        updated.env.allow_phase_a_embb_power_adjustment = False
        updated.env.force_embb_owner_per_rb = False
        updated.env.phase0_owner_fallback_policy = "sample_valid_non_snapshot"

        # Keep the "clean" control (no shield / rewrite / fallback / teacher / distill / BC).
        updated.shield.enable_feasibility_shield = False
        updated.shield.apply_joint_reliability_rewrite = False
        updated.shield.enable_greedy_fallback = False
        updated.training.use_greedy_reference_bc = False
        updated.training.use_teacher_distillation = False
        updated.training.teacher_distill_coef = 0.0
        updated.training.greedy_bc_coef = 0.0
        updated.training.teacher_guidance_scale = 0.0
        updated.training.bc_episodes = 0
        updated.training.bc_epochs = 0
